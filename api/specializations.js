export function detectSpecializations(text) {
  if (!text) return ['عمومی'];
  const lower = text.toLowerCase();
  const detected = [];

  for (const [key, spec] of Object.entries(SPECIALIZATIONS)) {
    for (const kw of spec.keywords) {
      if (lower.includes(kw)) {
        detected.push(spec.name);
        break;
      }
    }
  }

  return detected.length > 0 ? detected.slice(0, 3) : ['عمومی'];
}

export function buildSpecPrompt(specs) {
  if (!specs || specs.length === 0 || specs[0] === 'عمومی') return '';
  return `\n\nتخصص‌های فعال: ${specs.join('، ')}\nاز منظر این تخصص‌ها پاسخ بده. اصطلاحات تخصصی استفاده کن. اگر چند تخصص با هم ترکیب شده، ارتباط بین‌رشته‌ای رو نشون بده.`;
}
